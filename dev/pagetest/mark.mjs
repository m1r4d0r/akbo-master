import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({ ...(process.env.CHROME ? { executablePath: process.env.CHROME } : {}), args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
const errs = [];
page.on('pageerror', e => errs.push(e.message));
page.on('console', m => { if (m.type() === 'error' && !/fonts\.googleapis|ERR_/.test(m.text())) errs.push(m.text()); });
await page.goto(new URL('../../index.html', import.meta.url).href);
await page.waitForTimeout(300);
// 짧은 가락으로 바꿔 끝까지 가는 것을 본다
if (await page.locator('#io').isHidden()) await page.click('#tgIo'); await page.fill('#src', '제목 시험\n박자 4/4\n빠르기 200\n도 레 미 파 | 솔 라 시 도\' | 레\' 미\' 파\' 솔\' ||'); await page.click('#xApply'); await page.waitForTimeout(300); await page.click('#tgIo');
const st = () => page.evaluate(() => ({ on: [...document.querySelectorAll('.nt.on')].map(e => e.dataset.n), mark: [...document.querySelectorAll('.nt.mark')].map(e => e.dataset.n), btn: document.getElementById('play').textContent }));
console.log('처음', JSON.stringify(await st()));
await page.locator('.nt[data-n="6"]').click({ force: true });
await page.waitForTimeout(200);
console.log('7번째 음을 누름', JSON.stringify(await st()));
await page.screenshot({ path: 'mark.png', clip: { x: 0, y: 60, width: 1100, height: 240 } });
await page.click('#play');
await page.waitForTimeout(250);
console.log('재생 직후', JSON.stringify(await st()));
await page.waitForTimeout(2600);
console.log('끝난 뒤', JSON.stringify(await st()));
await page.click('#loop'); await page.click('#play');
await page.waitForTimeout(2300);
console.log('되풀이 한 바퀴 뒤', JSON.stringify(await st()));
await page.click('#play');
await page.click('#rew');
await page.waitForTimeout(100);
console.log('처음으로', JSON.stringify(await st()));
console.log('errors', JSON.stringify(errs));
await browser.close();
